CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  salt TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  role TEXT NOT NULL DEFAULT 'user',
  status TEXT NOT NULL DEFAULT 'active',
  avatar TEXT NOT NULL DEFAULT '',
  remark TEXT NOT NULL DEFAULT '',
  login_count INTEGER NOT NULL DEFAULT 0 CHECK (login_count >= 0),
  last_login_at TIMESTAMPTZ,
  last_login_ip TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  permissions JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(permissions) = 'array'),
  built_in SMALLINT NOT NULL DEFAULT 0 CHECK (built_in IN (0, 1)),
  sort INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  station TEXT NOT NULL DEFAULT '',
  kilometer TEXT NOT NULL DEFAULT '',
  direction TEXT NOT NULL DEFAULT '',
  type TEXT NOT NULL DEFAULT '进站信号机',
  status TEXT NOT NULL DEFAULT 'green',
  temperature DOUBLE PRECISION NOT NULL DEFAULT 0,
  humidity DOUBLE PRECISION NOT NULL DEFAULT 0,
  voltage DOUBLE PRECISION NOT NULL DEFAULT 0,
  current DOUBLE PRECISION NOT NULL DEFAULT 0,
  light_intensity DOUBLE PRECISION NOT NULL DEFAULT 0,
  signal_strength DOUBLE PRECISION NOT NULL DEFAULT 0,
  online SMALLINT NOT NULL DEFAULT 1 CHECK (online IN (0, 1)),
  lamp_hours INTEGER NOT NULL DEFAULT 0 CHECK (lamp_hours >= 0),
  remark TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS alarms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  signal_code TEXT NOT NULL DEFAULT '',
  device_type TEXT NOT NULL DEFAULT 'signal',
  level TEXT NOT NULL DEFAULT 'minor',
  title TEXT NOT NULL,
  content TEXT NOT NULL DEFAULT '',
  suggestion TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending',
  source TEXT NOT NULL DEFAULT '系统自检',
  occurred_at TIMESTAMPTZ NOT NULL,
  handled_by TEXT NOT NULL DEFAULT '',
  handled_at TIMESTAMPTZ,
  remark TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS work_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT '故障处理',
  priority TEXT NOT NULL DEFAULT 'medium',
  status TEXT NOT NULL DEFAULT 'pending',
  assignee TEXT NOT NULL DEFAULT '',
  station TEXT NOT NULL DEFAULT '',
  alarm_code TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  remark TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  finished_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS telemetry_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL DEFAULT 'unknown',
  device TEXT NOT NULL DEFAULT 'unknown',
  distance_cm DOUBLE PRECISION,
  distance_m DOUBLE PRECISION,
  water_active SMALLINT CHECK (water_active IN (0, 1)),
  wifi_ip TEXT NOT NULL DEFAULT '',
  uptime_ms BIGINT,
  ts_ms BIGINT,
  raw JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL DEFAULT 0,
  username TEXT NOT NULL DEFAULT '',
  title TEXT NOT NULL DEFAULT '新会话',
  model TEXT NOT NULL DEFAULT '',
  message_count INTEGER NOT NULL DEFAULT 0 CHECK (message_count >= 0),
  source TEXT NOT NULL DEFAULT 'agent',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES ai_sessions(id) ON DELETE CASCADE,
  role TEXT NOT NULL,
  content TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  tokens INTEGER NOT NULL DEFAULT 0 CHECK (tokens >= 0),
  latency_ms INTEGER NOT NULL DEFAULT 0 CHECK (latency_ms >= 0),
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_models (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL DEFAULT '',
  provider TEXT NOT NULL DEFAULT 'ollama',
  family TEXT NOT NULL DEFAULT '',
  parameter_size TEXT NOT NULL DEFAULT '',
  quantization TEXT NOT NULL DEFAULT '',
  size_bytes BIGINT NOT NULL DEFAULT 0 CHECK (size_bytes >= 0),
  description TEXT NOT NULL DEFAULT '',
  tags TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'catalog',
  is_default SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  sort INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS login_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL DEFAULT 0,
  username TEXT NOT NULL DEFAULT '',
  ip TEXT NOT NULL DEFAULT '',
  user_agent TEXT NOT NULL DEFAULT '',
  success SMALLINT NOT NULL DEFAULT 1 CHECK (success IN (0, 1)),
  message TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS op_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL DEFAULT 0,
  username TEXT NOT NULL DEFAULT '',
  action TEXT NOT NULL DEFAULT '',
  target_type TEXT NOT NULL DEFAULT '',
  target_id TEXT NOT NULL DEFAULT '',
  detail TEXT NOT NULL DEFAULT '',
  ip TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS password_resets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  username TEXT NOT NULL DEFAULT '',
  token TEXT NOT NULL UNIQUE,
  used SMALLINT NOT NULL DEFAULT 0 CHECK (used IN (0, 1)),
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS system_configs (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_phone_nonempty ON users (phone) WHERE phone <> '';
CREATE INDEX IF NOT EXISTS idx_alarms_status ON alarms (status);
CREATE INDEX IF NOT EXISTS idx_alarms_occurred ON alarms (occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_alarms_signal ON alarms (signal_code);
CREATE INDEX IF NOT EXISTS idx_work_orders_status_created ON work_orders (status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_created ON telemetry_records (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_device_created ON telemetry_records (device_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_ai_sessions_user_updated ON ai_sessions (user_id, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_ai_messages_session ON ai_messages (session_id, created_at, id);
CREATE INDEX IF NOT EXISTS idx_ai_models_default_sort ON ai_models (is_default DESC, sort, id);
CREATE INDEX IF NOT EXISTS idx_login_logs_created ON login_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_op_logs_created ON op_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_password_resets_user_used ON password_resets (user_id, used, expires_at);
